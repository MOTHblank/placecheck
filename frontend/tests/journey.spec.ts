import { expect, test } from "@playwright/test";

test("search, pagination, URL navigation, comparison, history and intercepted redirect", async ({ page, context, request }, testInfo) => {
  const consoleErrors: string[] = [];
  page.on("pageerror", (error) => consoleErrors.push(error.message));
  await page.goto("/");
  await page.getByPlaceholder("Cidade, bairro ou região").fill("Testópolis");
  await page.getByRole("button", { name: "Buscar imóveis", exact: true }).click();
  await expect(page.getByText("14 imóveis encontrados", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Ordenar resultados")).toBeVisible();
  await page.getByLabel("Ordenar resultados").selectOption("price");
  await expect(page).toHaveURL(/ordering=price/);
  await expect(page.getByText("Dados de demonstração", { exact: false })).toHaveCount(0);
  await page.getByRole("button", { name: "Próxima", exact: true }).click();
  await expect(page.getByText("Página 2 de 2")).toBeVisible();
  const paginatedUrl = page.url();
  await page.reload();
  await expect(page.getByText("Página 2 de 2")).toBeVisible();
  await page.getByRole("button", { name: "Anterior", exact: true }).click();
  await expect(page.getByText("Página 1 de 2")).toBeVisible();
  await page.goBack();
  await expect(page).toHaveURL(paginatedUrl);
  await expect(page.getByText("Página 2 de 2")).toBeVisible();
  await page.goForward();
  await page.getByRole("button", { name: /Ver ofertas/ }).first().click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("heading", { name: "Comparar ofertas" })).toBeVisible();
  await expect(dialog.locator(".offer-item")).toHaveCount(2);
  await dialog.getByText("Histórico de preços", { exact: true }).first().click();
  await expect(dialog.getByText(/650.000/).first()).toBeVisible();
  const detailUrl = page.url();
  await page.reload();
  await expect(dialog.locator(".offer-item")).toHaveCount(2);
  await expect(page).toHaveURL(detailUrl);
  const link = dialog.getByRole("link", { name: /Ver anúncio original/ }).first();
  const out = await link.getAttribute("href");
  const response = await request.get(out!, { maxRedirects: 0 });
  expect(response.status()).toBe(302);
  const destination = response.headers().location;
  expect(destination).toMatch(/^https:\/\/fixture\.invalid\/oferta\/\d+$/);
  let intercepted = "";
  // Exercise the real endpoint; stop navigation at its external redirect boundary.
  await context.route("**/out/**", async (route) => {
    const upstream = await route.fetch({ maxRedirects: 0 });
    expect(upstream.status()).toBe(302);
    intercepted = upstream.headers().location;
    await route.fulfill({ status: 200, contentType: "text/html", body: "External navigation intercepted" });
  });
  await page.screenshot({ path: testInfo.outputPath("comparison.png"), fullPage: true });
  const popupPromise = page.waitForEvent("popup");
  await link.click();
  const popup = await popupPromise;
  await expect(popup.getByText("External navigation intercepted")).toBeVisible();
  expect(intercepted).toBe(destination);
  expect(consoleErrors).toEqual([]);
  await popup.close();
});

test("loading, recoverable error, empty results and demo labels", async ({ page }) => {
  await page.route("**/api/properties/?**", (route) => route.fulfill({ status: 503, body: "unavailable" }));
  await page.goto("/");
  await expect(page.getByRole("alert")).toContainText("Não foi possível carregar");
  await page.unroute("**/api/properties/?**");
  let release!: () => void;
  const held = new Promise<void>((resolve) => { release = resolve; });
  await page.route("**/api/properties/?**", async (route) => { await held; await route.continue(); });
  await page.getByRole("button", { name: "Tentar novamente" }).click();
  await expect(page.getByLabel("Carregando imóveis")).toBeVisible();
  release();
  await expect(page.getByRole("button", { name: /Ver ofertas/ }).first()).toBeVisible();
  await page.unroute("**/api/properties/?**");
  await page.getByPlaceholder("Cidade, bairro ou região").fill("Sem inventário aqui");
  await page.getByRole("button", { name: "Buscar imóveis", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Nenhum imóvel encontrado" })).toBeVisible();
  await page.getByPlaceholder("Cidade, bairro ou região").fill("Belo Horizonte");
  await page.getByRole("button", { name: "Buscar imóveis", exact: true }).click();
  await expect(page.getByText("Inclui dados de demonstração").first()).toBeVisible();
  await page.getByRole("button", { name: /Ver ofertas/ }).first().click();
  await expect(page.getByText("Anúncio fictício para testes. Não há um site de origem real.").first()).toBeVisible();
  await expect(page.getByRole("dialog").getByRole("link", { name: /Ver anúncio original/ })).toHaveCount(0);
});
